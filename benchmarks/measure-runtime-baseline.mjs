import { execFileSync } from 'node:child_process';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { brotliCompressSync, gzipSync, constants } from 'node:zlib';

const root = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '..',
);
const reportPath = path.join(
  root,
  'benchmarks',
  'baselines',
  'runtime-reduction.json',
);
const summaryPath = path.join(
  root,
  'benchmarks',
  'baselines',
  'runtime-reduction.md',
);
const verify = process.argv.includes('--verify');
const wasmTemp = path.join(root, '.tmp', 'wasm-pack');
const commandForHost = (command, args) =>
  process.platform === 'win32'
    ? [
        process.env.ComSpec ?? 'cmd.exe',
        ['/d', '/s', '/c', [command, ...args].join(' ')],
      ]
    : [command, args];

function run(command, args) {
  const [hostCommand, hostArgs] = commandForHost(command, args);
  execFileSync(hostCommand, hostArgs, {
    cwd: root,
    stdio: 'inherit',
    env: { ...process.env, TMP: wasmTemp, TEMP: wasmTemp },
  });
}
function version(command, args = ['--version']) {
  const [hostCommand, hostArgs] = commandForHost(command, args);
  return execFileSync(hostCommand, hostArgs, {
    cwd: root,
    encoding: 'utf8',
  }).trim();
}
async function bytes(relativePath) {
  const value = await readFile(path.join(root, relativePath));
  return {
    path: relativePath.replace(/\\/g, '/'),
    raw: value.byteLength,
    gzip: gzipSync(value).byteLength,
    brotliQ11: brotliCompressSync(value, {
      params: { [constants.BROTLI_PARAM_QUALITY]: 11 },
    }).byteLength,
  };
}
async function collect() {
  // These are intentionally the same release commands developers and CI use.
  await mkdir(wasmTemp, { recursive: true });
  run('yarn', ['workspace', 'plec-runtime', 'build:wasm']);
  run('yarn', ['workspace', '@wasm-runtime/fullstack', 'build']);
  const artifacts = await Promise.all([
    bytes(
      'packages/plec-runtime/crates/runtime/dist/runtime/runtime_bg.wasm',
    ),
    bytes(
      'packages/plec-runtime/crates/runtime/dist/runtime/runtime.js',
    ),
    bytes('apps/fullstack/dist/public/runtime/runtime_bg.wasm'),
    bytes('apps/fullstack/dist/public/runtime/runtime.js'),
    bytes('apps/fullstack/dist/public/route-manifest.json'),
  ]);
  const graphDirectory = path.join(
    root,
    'apps/fullstack/dist/public/graphs',
  );
  const { readdir } = await import('node:fs/promises');
  for (const name of (await readdir(graphDirectory)).sort())
    if (name.endsWith('.json'))
      artifacts.push(
        await bytes(
          path.join('apps/fullstack/dist/public/graphs', name),
        ),
      );
  return { artifacts };
}
function comparable(result) {
  return JSON.stringify(result.artifacts);
}
function markdown(report) {
  const headers = [
    'Artifact',
    'Raw bytes',
    'Gzip bytes',
    'Brotli Q11 bytes',
  ];
  const rows = report.artifacts.map((artifact) => [
    `\`${artifact.path}\``,
    String(artifact.raw),
    String(artifact.gzip),
    String(artifact.brotliQ11),
  ]);
  const widths = headers.map((header, index) =>
    Math.max(header.length, ...rows.map((row) => row[index].length)),
  );
  const render = (row) =>
    `| ${row
      .map((cell, index) =>
        index === 0
          ? cell.padEnd(widths[index])
          : cell.padStart(widths[index]),
      )
      .join(' | ')} |`;
  const separator = `| ${'-'.repeat(widths[0])} | ${widths
    .slice(1)
    .map((width) => `${'-'.repeat(width - 1)}:`)
    .join(' | ')} |`;
  return `# Runtime reduction baseline\n\nGenerated by \`yarn measure:runtime-baseline\`. Compression is gzip and Brotli quality 11.\n\n${render(headers)}\n${separator}\n${rows.map(render).join('\n')}\n`;
}

const first = await collect();
if (verify) {
  const second = await collect();
  if (comparable(first) !== comparable(second))
    throw new Error('NONDETERMINISTIC_RUNTIME_BASELINE');
}
const report = {
  schemaVersion: 1,
  commands: [
    'yarn workspace plec-runtime build:wasm',
    'yarn workspace @wasm-runtime/fullstack build',
  ],
  toolchain: {
    node: process.version,
    yarn: version('yarn'),
    rustc: version('rustc'),
    cargo: version('cargo'),
    wasmPack: version('wasm-pack'),
    wasmTarget:
      version('rustup', ['target', 'list', '--installed'])
        .split(/\r?\n/)
        .find((target) =>
          target.startsWith('wasm32-unknown-unknown'),
        ) ?? 'missing',
  },
  buildProfile: {
    wasmOpt: false,
    brotliQuality: 11,
  },
  ...first,
};
await mkdir(path.dirname(reportPath), { recursive: true });
await writeFile(reportPath, `${JSON.stringify(report, null, 2)}\n`);
await writeFile(summaryPath, markdown(report));
